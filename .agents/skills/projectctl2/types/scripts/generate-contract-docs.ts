#!/usr/bin/env bun
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

import { DOCUMENT_SCHEMAS, SCHEMA_FILES, type SchemaName } from './schema-validator.ts';

const generatedDir = resolve(import.meta.dir, '../generated');
const output = resolve(import.meta.dir, '../../requirements/contracts.md');
const navigationId = DOCUMENT_SCHEMAS.navigation.meta()?.id as string;
function contractTitle(name: SchemaName): string {
  const title = DOCUMENT_SCHEMAS[name].meta()?.title;
  if (typeof title !== 'string' || !title) throw new Error(`Contract ${name} is missing its canonical meta().title.`);
  return title;
}
type Schema = Record<string, any>;

function resolveSchema(schema: Schema, root: Schema, external?: Schema, resolving = new Set<string>()): Schema {
  const ref = schema.$ref as string | undefined;
  if (!ref) return schema;
  if (resolving.has(ref)) return schema;
  resolving.add(ref);
  let target: Schema | undefined;
  if (ref.startsWith('#/$defs/')) target = root.$defs?.[ref.slice('#/$defs/'.length)];
  else if (ref.includes(`${navigationId}#/$defs/criterion`)) {
    external ??= JSON.parse(readFileSync(join(generatedDir, SCHEMA_FILES.navigation), 'utf8')) as Schema;
    target = external.$defs?.criterion;
  }
  if (!target) return schema;
  return { ...resolveSchema(target, root, external, resolving), ...schema, $ref: undefined };
}

function typeOf(schema: Schema): string {
  if (schema.const !== undefined) return `const ${JSON.stringify(schema.const)}`;
  if (schema.enum) return schema.enum.map((value: unknown) => `\`${String(value)}\``).join(', ');
  if (schema.oneOf || schema.anyOf) return 'union';
  if (schema.type === 'array') return `array<${typeOf(schema.items ?? {})}>`;
  if (schema.type === 'object' || schema.properties) return 'object';
  return schema.type ?? 'any';
}

function constraints(schema: Schema): string {
  const values: string[] = [];
  if (schema.const !== undefined) values.push(`const ${JSON.stringify(schema.const)}`);
  if (schema.enum) values.push(`allowed: ${schema.enum.map((v: unknown) => `\`${String(v)}\``).join(', ')}`);
  for (const key of ['minLength', 'maxLength', 'minItems', 'maxItems', 'minimum', 'maximum', 'pattern', 'uniqueItems']) {
    if (schema[key] !== undefined) values.push(`${key}: ${String(schema[key])}`);
  }
  if (schema.additionalProperties === false) values.push('unknown fields rejected');
  if (schema.allOf) values.push('all listed constraints apply');
  return values.join('; ') || '—';
}

function renderDocument(name: SchemaName, title: string, root: Schema): string {
  const rows: string[] = [];
  const seen = new Set<string>();
  function visit(input: Schema, path: string, required: boolean, inheritedDescription?: string): void {
    const schema = resolveSchema(input, root);
    const identity = `${path}:${JSON.stringify(schema)}`;
    if (seen.has(identity)) return;
    seen.add(identity);
    const description = schema.description ?? inheritedDescription;
    if (path) rows.push(`| \`${path}\` | ${typeOf(schema)} | ${required ? 'Yes' : 'No'} | ${constraints(schema)} | ${description ? description.replaceAll('|', '\\|') : '—'} |`);
    if (schema.oneOf) {
      for (const option of schema.oneOf) visit(option, path, required, description);
    }
    if (schema.anyOf) for (const option of schema.anyOf) visit(option, path, required, description);
    if (schema.type === 'array' && schema.items) visit(schema.items, `${path}[]`, true, description);
    if (schema.properties) {
      const requiredKeys = new Set<string>(schema.required ?? []);
      for (const [key, child] of Object.entries(schema.properties as Record<string, Schema>)) {
        visit(child, path ? `${path}.${key}` : key, requiredKeys.has(key));
      }
    }
  }
  visit(root, '', true);
  const resolvedRoot = resolveSchema(root, root);
  const rootSummary = resolvedRoot.description
    ?? resolvedRoot.oneOf?.map((option: Schema) => resolveSchema(option, root).description).filter(Boolean).join(' ');
  const summary = rootSummary ? `${rootSummary}\n\n` : '';
  return `## ${title} (${name})\n\nSource: [generated JSON Schema](../types/generated/${SCHEMA_FILES[name]}); canonical Zod contract and inferred TypeScript type: [\`${title}\`](../types/contracts/${name}.ts).\n\n${summary}| Field | Type | Required | Allowed values / constraints | Description |\n|---|---|---:|---|---|\n${rows.join('\n')}\n`;
}

export function renderContractDocs(): string {
const documentNames = Object.keys(DOCUMENT_SCHEMAS) as SchemaName[];
const sections = documentNames.map(name => {
  const title = contractTitle(name);
  const schema = JSON.parse(readFileSync(join(generatedDir, SCHEMA_FILES[name]), 'utf8')) as Schema;
  return renderDocument(name, title, schema);
});
return `<!-- Generated by bun .agents/skills/projectctl2/types/scripts/generate-contract-docs.ts; do not edit by hand. -->\n# Shared data contract reference\n\nThis reference is generated from the exported Draft 2020-12 JSON Schemas. Zod definitions in \`types/contracts/\` are canonical and infer the TypeScript types; only the JSON Schemas are generated artifacts. See each consuming skill for semantic checks that extend structural validation.\n\n${sections.join('\n')}\n`;
}

if (import.meta.main && process.argv.includes('--check')) {
  const content = renderContractDocs();
  let current = '';
  try { current = readFileSync(output, 'utf8'); } catch { /* stale/missing */ }
  if (current !== content) {
    console.error(`Contract reference is stale; run bun .agents/skills/projectctl2/types/scripts/generate-contract-docs.ts\n- ${output}`);
    process.exitCode = 1;
  } else console.log('Generated contract reference is up to date.');
} else if (import.meta.main) {
  const content = renderContractDocs();
  writeFileSync(output, content);
  console.log(`Generated ${output}`);
}
